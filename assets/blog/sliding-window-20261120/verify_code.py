def extract(text, lang):
    return re.findall(r"```" + lang + r"\n(.*?)```", text, re.S)


def brute_min_window(s, t):
    """Shortest window covering t; '' when t is empty or nothing covers t."""
    if not t:
        return ""
    need = Counter(t)
    best = None
    for i in range(len(s)):
        for j in range(i + 1, len(s) + 1):
            if not need - Counter(s[i:j]):
                if best is None or j - i < len(best):
                    best = s[i:j]
    return best or ""


def brute_inclusion(t, s):
    if not t:
        return True
    m = len(t)
    key = sorted(t)
    return any(sorted(s[i:i + m]) == key for i in range(len(s) - m + 1))


def brute_anagrams(s, t):
    if not t:
        return list(range(len(s) + 1))
    m, key = len(t), sorted(t)
    return [i for i in range(len(s) - m + 1) if sorted(s[i:i + m]) == key]


def brute_longest(s):
    best = 0
    for i in range(len(s)):
        seen = set()
        for j in range(i, len(s)):
            if s[j] in seen:
                break
            seen.add(s[j])
            best = max(best, j - i + 1)
    return best


def brute_min_subarray_len(target, nums):
    best = None
    for i in range(len(nums)):
        total = 0
        for j in range(i, len(nums)):
            total += nums[j]
            if total >= target:
                best = j - i + 1 if best is None else min(best, j - i + 1)
                break
    return 0 if best is None else best


def brute_num_subarray_product(nums, k):
    if k <= 1:
        return 0
    count = 0
    for i in range(len(nums)):
        prod = 1
        for j in range(i, len(nums)):
            prod *= nums[j]
            if prod < k:
                count += 1
            else:
                break
    return count


def brute_strstr(text, pattern):
    if not pattern:
        return 0
    return text.find(pattern)


def brute_repeated_dna(s):
    seen, out = set(), []
    for i in range(len(s) - 9):
        sub = s[i:i + 10]
        if sub in seen and sub not in out:
            out.append(sub)
        seen.add(sub)
    return sorted(out)


